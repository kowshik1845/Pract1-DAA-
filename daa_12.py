# Travelling Salesman Problem

from itertools import permutations

def tsp(graph, start):
    n = len(graph)
    vertices = [i for i in range(n) if i != start]

    min_cost = float('inf')
    best_path = []

    for path in permutations(vertices):
        cost = 0
        k = start

        for j in path:
            cost += graph[k][j]
            k = j

        cost += graph[k][start]

        if cost < min_cost:
            min_cost = cost
            best_path = [start] + list(path) + [start]

    print("Minimum Cost:", min_cost)
    print("Best Path:", best_path)


# Main Program
graph = [
    [0, 10, 15, 20],
    [10, 0, 35, 25],
    [15, 35, 0, 30],
    [20, 25, 30, 0]
]

tsp(graph, 0)